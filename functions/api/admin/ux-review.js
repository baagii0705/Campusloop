export async function onRequestPost({request, env}) {
  if (!originOK(request) || !await requireAdmin(request)) {
    return response({error: 'Админ эрх шаардлагатай.'}, 403);
  }
  if (!env?.SOLIO_UX_AI) {
    return response({error: 'Зураг шалгах үйлчилгээний холболт идэвхгүй байна.'}, 503);
  }

  let input;
  try {
    input = await readJSON(request, 2_100_000);
  } catch (error) {
    return response({error: error.message}, 400);
  }
  const {image, goal = ''} = input;
  if (typeof image !== 'string' ||
      !/^data:image\/(?:png|jpeg|webp);base64,[A-Za-z0-9+/]+={0,2}$/.test(image) ||
      typeof goal !== 'string' || goal.length > 250) {
    return response({error: 'PNG, JPEG эсвэл WebP зураг сонгоно уу.'}, 400);
  }

  try {
    const result = await env.SOLIO_UX_AI.run('@cf/google/gemma-4-26b-a4b-it', {
      messages: [
        {role: 'system', content: instructions},
        {role: 'user', content: [
          {type: 'text', text: goal ? 'Оюутны зорилго: ' + goal : 'Sol1o-ийн энэ дэлгэцийг шалга.'},
          {type: 'image_url', image_url: {url: image}},
        ]},
      ],
      max_tokens: 1000,
      temperature: 0.2,
    });
    const review = result.choices?.[0]?.message?.content ?? result.response;
    if (typeof review !== 'string' || !review.trim()) throw Error('Empty review');
    return response({review: review.trim()});
  } catch {
    return response({error: 'Зургийг шалгаж чадсангүй. Дахин оролдоно уу.'}, 502);
  }
}
